export function displayStatusLabel(value?: string | null): string {
  if (!value?.trim()) return 'Chưa ghi nhận'
  const normalized = value.trim().replace(/-/g, '_').toUpperCase()
  return labels[normalized] ?? (/[À-ỹ]/.test(value) ? value : 'Chưa xác định')
}

export function displayRoleLabel(value: string): string {
  const roles: Record<string, string> = { CUSTOMER: 'Khách hàng', STAFF: 'Nhân viên', MANAGER: 'Quản lý cơ sở', BUSINESS: 'Ban điều hành', ADMIN: 'Quản trị viên' }
  return roles[value.toUpperCase()] ?? 'Người dùng'
}
